#!/usr/bin/env bash
# Проверки входных документов системы: README, OVERVIEW, STATUS.
#
# Зачем отдельный файл: тесты системы проверяли шаблоны, скиллы, форматы состояния
# и чистоту ядра, но ни один не смотрел на документы, которые читает человек. Сверка
# 08.08.2026 дала шестнадцать расхождений, и самое вредное из них было **инструкцией**:
# README учил подключать канал через плагин, который к тому моменту обязан быть
# выключен. Новый пользователь, действуя строго по README, сам ломал бы себе приём
# уведомлений — молча, потому что выбитый слушатель не жалуется, а бот выглядит живым.
#
# Проверяется только механизируемое. Полевой опыт, состояние пилота и актуальность
# сравнений остаются ручной сверкой — у неё свой триггер (готовность изменения).
#
# Аргумент — корень проверяемой копии (для негативных прогонов на испорченной).
set -euo pipefail
shopt -s nullglob

FORGE_HOME="$(cd "$(dirname "$0")/.." && pwd)"
ROOT="${1:-$FORGE_HOME}"

fail() { echo "FAIL: $1"; exit 1; }

README="$ROOT/README.md"
STATUS="$ROOT/docs/STATUS.md"
OVERVIEW="$ROOT/docs/OVERVIEW.md"

for f in "$README" "$STATUS" "$OVERVIEW"; do
  [[ -f "$f" ]] || fail "нет входного документа: ${f#$ROOT/}"
done

# ─── 1. Дата снимка не раньше событий, которые он описывает ───────────────────
# Дока, которая называет свою дату и описывает более поздние события, хуже даты не
# называющей: читатель верит шапке, а шапка — единственное, по чему он судит о
# возрасте документа. Ссылка на снимок стоит в README как входная точка.
norm_dates() {
  # ДД.ММ.ГГГГ и ГГГГ-ММ-ДД → ГГГГММДД, по строке на дату
  grep -ohE '\b[0-9]{2}\.[0-9]{2}\.[0-9]{4}\b|\b[0-9]{4}-[0-9]{2}-[0-9]{2}\b' "$1" \
    | awk '{ if (index($0,".")) { split($0,p,"."); printf "%s%s%s\n", p[3],p[2],p[1] }
             else { gsub(/-/,""); print } }'
}

header_date="$(head -5 "$STATUS" | norm_dates /dev/stdin | head -1)"
[[ -n "$header_date" ]] || fail "STATUS.md — в шапке нет даты снимка"
# Будущие даты — это сроки и планы («перепроверить такого-то»), а не события:
# снимок не может описывать то, чего ещё не было, поэтому сравниваем только с
# прошедшими. Без этой оговорки любой запланированный срок валит проверку.
today="$(date +%Y%m%d)"
latest="$(norm_dates "$STATUS" | sort -n | awk -v t="$today" '$1 <= t' | tail -1)"
if [[ "$header_date" -lt "$latest" ]]; then
  echo "FAIL: STATUS.md — дата снимка ($header_date) раньше самого позднего упомянутого события ($latest)"
  echo "      Пересобери снимок по фактическому состоянию, а не правь дату: правка даты"
  echo "      без пересборки превращает устаревший документ в неверное утверждение."
  exit 1
fi

# ─── 2. Инвентарь шаблонов: каждый упомянут в дереве «Что где лежит» ──────────
# Инвентарь, который мирно расходится с деревом файлов, — главный источник дрейфа:
# на сверке в README не хватало block-agent-brief.md, то есть самого нагруженного
# шаблона системы.
for tpl in "$ROOT"/templates/*.md; do
  name="$(basename "$tpl")"
  grep -qF "$name" "$README" || fail "README не упоминает шаблон $name — инвентарь разошёлся с деревом файлов"
done

# ─── 3. Живость относительных ссылок ─────────────────────────────────────────
for doc in "$README" "$STATUS" "$OVERVIEW"; do
  base="$(dirname "$doc")"
  while IFS= read -r link; do
    [[ -z "$link" ]] && continue
    target="${link%%#*}"
    [[ -z "$target" ]] && continue
    [[ -e "$base/$target" ]] || fail "${doc#$ROOT/} ссылается на несуществующий путь: $target"
  done < <(grep -ohE '\]\([^)]+\)' "$doc" | sed 's/^](//; s/)$//' \
           | grep -vE '^(https?:|mailto:|#)' || true)
done

# ─── 4. У каждой команды в README есть фраза вызова из её же триггеров ────────
# Команды вызываются словами, а не именем скилла. Если фразы нет в README —
# человек не знает, чем позвать; если она есть, но не совпадает с триггерами
# скилла — он позовёт и не дозовётся. На сверке у раскатки фразы не было вовсе.
for dir in "$ROOT"/skills/*/; do
  skill="$(basename "${dir%/}")"
  desc="$(sed -n '2,6p' "${dir}SKILL.md" | grep -m1 '^description:' || true)"
  [[ -n "$desc" ]] || fail "[$skill] нет описания — триггеры брать неоткуда"
  found=0
  while IFS= read -r phrase; do
    [[ -z "$phrase" ]] && continue
    if grep -qiF "$phrase" "$README"; then found=1; break; fi
  done < <(grep -oE '"[^"]+"' <<< "$desc" | tr -d '"')
  (( found == 1 )) || fail "[$skill] ни одна его фраза вызова не встречается в README — позвать команду нечем"
done

# ─── 5. Запрещённые инструкции ───────────────────────────────────────────────
# Плагин Telegram обязан быть выключен: он поднимает второго слушателя того же
# бота, а Telegram допускает одного — второй выбивает первого, и выбитый молча
# перестаёт получать сообщения при живом с виду боте. Документ, который учит его
# включить, ломает читателя тише, чем неверный факт.
for doc in "$README" "$STATUS" "$OVERVIEW"; do
  while IFS= read -r line; do
    grep -qiE 'выключ|отключ|нельзя|запрещ|не использ' <<< "$line" && continue
    echo "FAIL: ${doc#$ROOT/} — плагин Telegram упомянут как рабочий способ включить канал:"
    echo "      $line"
    echo "      Канал держит постоянная служба; второй слушатель бота молча выбивает первого."
    exit 1
  done < <(grep -inE 'плагин[а-я]* +telegram|telegram-плагин' "$doc" | cut -c1-160 || true)
done

echo "PASS"
