#!/usr/bin/env bash
set -euo pipefail
shopt -s nullglob

FORGE_HOME="$(cd "$(dirname "$0")/.." && pwd)"
# По умолчанию проверяются реальные скиллы репо; аргумент — каталог с копией
# (используется негативными прогонами на испорченных копиях).
SKILLS_DIR="${1:-$FORGE_HOME/skills}"
MAX_DESCRIPTION=1024

fail() { echo "FAIL: $1"; exit 1; }

found=0
for dir in "$SKILLS_DIR"/*/; do
  name="$(basename "${dir%/}")"
  skill="${dir}SKILL.md"
  [[ -f "$skill" ]] || fail "[$name] нет файла SKILL.md"
  found=1

  # 1. Шапка: name обязателен и обязан совпадать с именем каталога — иначе
  # харнесс и install.sh расходятся в том, как называется команда.
  [[ "$(sed -n '1p' "$skill")" == "---" ]] || fail "[$name] SKILL.md не начинается с YAML-шапки"
  # `|| true` обязателен: без него grep без совпадения роняет скрипт через set -e
  # раньше, чем выполнится проверка ниже, и тест падает молча, без диагностики.
  declared="$(sed -n '2,20p' "$skill" | grep -m1 '^name:' | sed 's/^name: *//' | tr -d '\r' || true)"
  [[ -n "$declared" ]] || fail "[$name] в шапке нет поля name"
  [[ "$declared" == "$name" ]] || fail "[$name] name в шапке ($declared) не совпадает с именем каталога"

  # 2. Описание: по нему модель решает, вызывать скилл или нет. Пустое описание
  # означает, что скилл не найдётся никогда.
  description="$(sed -n '2,20p' "$skill" | grep -m1 '^description:' | sed 's/^description: *//' || true)"
  [[ -n "$description" ]] || fail "[$name] в шапке нет поля description"
  desc_len="${#description}"
  (( desc_len <= MAX_DESCRIPTION )) || fail "[$name] description длиной $desc_len символов, лимит $MAX_DESCRIPTION"

  # 3. Все пути к шаблонам и тестам, которые скилл называет, обязаны
  # существовать. Это защита от молчаливого дрифта: переименовали шаблон —
  # скилл продолжает ссылаться на старое имя и ломается только в бою.
  while IFS= read -r ref; do
    [[ -z "$ref" ]] && continue
    target="$FORGE_HOME/$ref"
    if [[ "$ref" == */ ]]; then
      [[ -d "$target" ]] || fail "[$name] ссылается на несуществующий каталог: $ref"
    else
      [[ -e "$target" ]] || fail "[$name] ссылается на несуществующий файл: $ref"
    fi
  done < <(grep -ohE '\b(templates|test|agents)/[A-Za-z0-9_./-]*' "$skill" | sed 's/\.$//' | sort -u)

  echo "PASS: $name"
done

(( found == 1 )) || fail "не найдено ни одного скилла в $SKILLS_DIR"

# 3a. Скиллы, создающие задачи на GitHub, обязаны ссылаться на стандарт трекера.
# Без него тон и состав задачи задаёт каждый агент заново: в беклоге появлялись
# цитаты из переписки владельца, имена рабочей инфраструктуры и описания
# персональных данных — а трекер читают посторонние.
for creator in forge-build forge-new; do
  skill="$SKILLS_DIR/$creator/SKILL.md"
  [[ -f "$skill" ]] || continue
  grep -qF 'templates/issue-style.md' "$skill" || \
    fail "[$creator] создаёт задачи на GitHub, но не ссылается на templates/issue-style.md"
done

# 3b. Правила, добытые живыми прогонами. Проверяются по существу, а не по
# заголовку раздела: раздел можно переименовать, а вот исчезновение самой строки
# означает, что диспетчер снова повторит уже измеренный отказ. Каждая строка
# стоила отдельного разбора — сплошной `git add`, забравший чужой файл в чужой
# коммит, и стенды снятых копий, работавшие сутками после сдачи блока.
declare -a BUILD_RULES=(
  'git diff --cached --name-only'  # состав индекса сверяется до коммита
  'git add .`'                     # сплошной add назван запрещённым, а не «нежелательным»
  'возвращай копией'               # после проверки порчей файл восстанавливают копией, не git
  'до удаления папки'              # стенд блока гасится, пока compose-файл ещё доступен
  'docker compose ls'              # осиротевшие стенды ищутся на старте прогона
  'из свежего клона'               # тесты приёмки гоняются в клоне, а не в рабочей копии
  'Красный клон при зелёной'       # расхождение клона и копии означает «блок не принят»
  'сверь три числа'                # приёмка читает состав прогона, а не код возврата
  'строкой приёмки'                # числа прогона попадают в журнал, иначе сравнивать не с чем
  'Проходит не только счастливый'  # сверка со спекой обязана щупать отказы и права
  'относительным порогом'          # покрытие не ниже прошлой приёмки, а не абсолютные 80%
  'сверь со спекой сценарии'       # частичная сверка идёт на приёмке блока, не только в конце
  'caffeinate'                     # машина не засыпает, пока работают фоновые агенты
  'причина неизвестна'             # в журнал идёт проверенная причина, а не правдоподобная версия
  'не тратит попытку'              # обрыв по сну — отказ среды, а не негодный результат
  'живых исполнителей'             # перед правкой файлов блока проверяется, не работает ли субагент
  'Доделка диспетчером'            # мелкая доводка описана как штатный путь рядом с возвратом
  'граф отстал'                    # «нечего брать» отличается от «граф протух»
  'Засеки, сколько он идёт'        # длительность прогона замеряется и уходит в бриф
  'задаёт базу, а не заворачивает' # правило, введённое посреди стройки, не валит её задним числом
  'отказ канала, а не молчание'    # неответ канала не записывается как молчание владельца
  'а не весь список блока'         # приёмка спрашивает пункты этапа, а не всего блока
  'приём ответов отобран'          # 503 polling down на старте отличается от «канала нет»
  'сверь их с эталоном'            # экран блока сверяется с нарисованным, а не «похоже»
  'картой соответствия'            # модуль эталона без блока стройка не увидит
  'Проверь сам гейт порчей'        # зелёный гейт может честно считать не ту копию
  'копией, а не симлинком'         # симлинк на данные ломает относительные пути молча
  'Зови объявленную команду'       # приёмка не собирает команду прогона сама
  'пригодность пакета'             # стройка не идёт по пакету, по которому нечего строить
  'покажи это владельцу'           # блок, изменивший видимое человеку, показывается картинкой
  'спроси проверку контракта'      # блоки идут параллельно и не видят друг друга
)
build_skill="$SKILLS_DIR/forge-build/SKILL.md"
if [[ -f "$build_skill" ]]; then
  for rule in "${BUILD_RULES[@]}"; do
    grep -qF -- "$rule" "$build_skill" || {
      echo "FAIL: forge-build — потеряно правило, добытое прогоном: ${rule}"
      exit 1
    }
  done
fi

# Машинный отчёт прогона — стык трёх команд: forge-new объявляет его формат вместе
# с конфигами гейтов, forge-quality-gates называет его частью роли «тесты», приёмка
# в forge-build его читает. Выпадение любого звена возвращает гейт к коду возврата,
# который не отличает двести выполненных проверок от нуля зарегистрированных.
for pair in "forge-new|отчёта прогона и путь к нему" "forge-quality-gates|формат машинного отчёта прогона" \
            "forge-new|caffeinate" "forge-status|граф отстал от того, что" "forge-status|Показывай, но не помечай" \
            "forge-new|экранный эталон" "forge-new|Эталон пришёл позже" \
            "forge-new|scripts/check" "forge-new|core.hooksPath" \
            "forge-deploy|Смоук обязан остаться повторяемым" "forge-deploy|запиши способ отката" "forge-new|более позднего этапа" "forge-new|package.test.sh"; do
  IFS='|' read -r skill_name marker <<< "$pair"
  target="$SKILLS_DIR/$skill_name/SKILL.md"
  [[ -f "$target" ]] || continue
  grep -qF -- "$marker" "$target" || \
    fail "[$skill_name] потеряно правило, добытое прогоном: ${marker}"
done

# 4. Чистота ядра: скиллы и шаблоны обязаны работать у любого человека, а не
# только у владельца этой машины. Поэтому в них не должно быть ни зашитого адреса
# конкретного репозитория (`--repo владелец/имя`), ни абсолютных путей в домашний
# каталог. Имя владельца в проверке намеренно не упоминается — иначе оно само
# оказалось бы прописано в ядре. Адрес репозитория системы определяется из remote,
# личные пути живут в профиле пользователя.
# channel/ тоже ядро: он разворачивается у любого, кто поставит систему, поэтому
# ни чужих адресов репозиториев, ни абсолютных домашних путей в нём быть не должно.
# Файл baseline попадает в этот же список: AITriage записывает в него абсолютный
# путь до файла с находкой, а репозиторий общий — путь и утечёт, и не сработает на
# чужой машине. Сопоставление идёт по хешу, поэтому относительный путь безопасен.
for scope in "$SKILLS_DIR" "$FORGE_HOME/templates" "$FORGE_HOME/channel" "$FORGE_HOME/agents" "$FORGE_HOME/.aitriage-baseline.json"; do
  [[ -e "$scope" ]] || continue

  hardcoded_repo="$(grep -rnE -- '--repo[= ]+[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+' "$scope" || true)"
  [[ -z "$hardcoded_repo" ]] || {
    echo "FAIL: зашит конкретный репозиторий (адрес определяется из remote, а не пишется в ядро):"
    echo "$hardcoded_repo"
    exit 1
  }

  home_path="$(grep -rnE -- '(/Users/|/home/)[A-Za-z0-9]' "$scope" || true)"
  [[ -z "$home_path" ]] || {
    echo "FAIL: абсолютный путь в домашний каталог (личное живёт в профиле пользователя):"
    echo "$home_path"
    exit 1
  }

  # Путь с буквой диска или UNC — всегда чья-то конкретная машина. Ловится
  # отдельно от домашних путей: прошлая проверка искала только `/Users/` и
  # `/home/`, поэтому `C:\projects\...` в инструкции по каналу прожил незамеченным.
  machine_path="$(grep -rnE -- '([A-Za-z]:\\|\\\\[A-Za-z0-9])' "$scope" || true)"
  [[ -z "$machine_path" ]] || {
    echo "FAIL: путь на конкретной машине (в ядре пути параметризуются):"
    echo "$machine_path"
    exit 1
  }

  # Имена личной инфраструктуры владельца (его серверов, сетей, соседних
  # проектов) в ядре недопустимы, но перечислять их в самом ядре нельзя — они бы
  # тогда в нём и оказались. Поэтому список лежит у владельца:
  # ~/.claude/forge/private-names.txt, по одному слову в строке, регистр не важен.
  # Нет файла — проверка пропускается с явной строкой, а не молча.
  private_names="${FORGE_PRIVATE_NAMES:-$HOME/.claude/forge/private-names.txt}"
  if [[ -f "$private_names" ]]; then
    while IFS= read -r name; do
      name="$(echo "$name" | sed 's/#.*//' | xargs || true)"
      [[ -z "$name" ]] && continue
      hit="$(grep -rniF -- "$name" "$scope" || true)"
      [[ -z "$hit" ]] || {
        echo "FAIL: в ядре имя личной инфраструктуры (перечислено в $private_names):"
        echo "$hit"
        exit 1
      }
    done < "$private_names"
  else
    echo "NOTE: нет $private_names — имена личной инфраструктуры не проверяются"
  fi
done

# 5. Имена личной инфраструктуры не должны попадать и в документацию: репозиторий
# публичный, а доки читают снаружи. Проверка отделена от чистоты ядра — там
# запрещены ещё и зашитый адрес репозитория и абсолютные пути, а README обязан
# называть адрес клонирования и `~/.claude/...`. Повод: ревизия 26.08.2026 нашла
# в docs/ имя домашнего сервера, а в замере по тестам — имена шестнадцати личных и
# рабочих репозиториев вместе с их состоянием.
private_names="${FORGE_PRIVATE_NAMES:-$HOME/.claude/forge/private-names.txt}"
if [[ -f "$private_names" ]]; then
  for scope in "$FORGE_HOME/docs" "$FORGE_HOME/README.md"; do
    [[ -e "$scope" ]] || continue
    while IFS= read -r name; do
      name="$(echo "$name" | sed 's/#.*//' | xargs || true)"
      [[ -z "$name" ]] && continue
      hit="$(grep -rniF -- "$name" "$scope" || true)"
      [[ -z "$hit" ]] || {
        echo "FAIL: в документации имя личной инфраструктуры (перечислено в $private_names):"
        echo "$hit"
        exit 1
      }
    done < "$private_names"
  done
else
  echo "NOTE: нет $private_names — имена личной инфраструктуры в документации не проверяются"
fi

echo "PASS"
