#!/usr/bin/env bash
set -euo pipefail

# Тесты чистой логики канала. Гоняются без Docker и без сети: всё, что требует
# aiogram/asyncpg, живёт в других модулях и в core.py не импортируется намеренно —
# тогда решения о доступе проверяются без поднятого стека.
FORGE_HOME="$(cd "$(dirname "$0")/.." && pwd)"
BOT_DIR="${1:-$FORGE_HOME/channel/bot}"

[[ -d "$BOT_DIR" ]] || { echo "FAIL: каталог бота не найден: $BOT_DIR"; exit 1; }
for f in core.py test_core.py; do
  [[ -f "$BOT_DIR/$f" ]] || { echo "FAIL: нет $BOT_DIR/$f"; exit 1; }
done

# core.py обязан оставаться свободным от внешних зависимостей: как только в него
# попадёт aiogram или asyncpg, эти тесты перестанут гоняться на машине без Docker,
# и проверки доступа станет нечем проверить.
forbidden="$(grep -nE '^\s*(import|from)\s+(aiogram|aiohttp|asyncpg)' "$BOT_DIR/core.py" || true)"
[[ -z "$forbidden" ]] || {
  echo "FAIL: core.py потянул внешнюю зависимость — тесты логики перестанут работать без Docker:"
  echo "$forbidden"
  exit 1
}

# Запуск из каталога бота: core.py импортируется напрямую, без установки пакета.
# Вывод в переменную, а НЕ в конвейер: код возврата конвейера — это код последней
# команды (`tail`), то есть всегда 0, и «PASS» печаталось бы поверх упавших тестов.
if ! output="$( cd "$BOT_DIR" && python3 -m unittest -q test_core 2>&1 )"; then
  echo "$output" | tail -20
  echo "FAIL: тесты логики канала упали"
  exit 1
fi
echo "$output" | tail -3

# Пол по числу выполненных проверок. Без него «Ran 0 tests» даёт OK и нулевой код,
# и тест печатает PASS на наборе, где не выполнилось ничего: проверено мутацией —
# переименование всех 27 методов в disabled_* оставляло PASS. Зелёное на нуле
# выполненного не отличается от зелёного на всём наборе, поэтому число читается,
# а не подразумевается. Пол поднимается вместе с набором, вниз — только осознанно.
MIN_CHECKS=27
ran="$(printf '%s' "$output" | grep -oE '^Ran [0-9]+ test' | tail -1 | awk '{print $2}')"
[[ -n "$ran" ]] || { echo "FAIL: в выводе прогона нет строки «Ran N tests» — состав прогона неизвестен"; exit 1; }
(( ran >= MIN_CHECKS )) || {
  echo "FAIL: выполнено проверок $ran, ожидается не меньше $MIN_CHECKS — часть набора не выполнилась"
  exit 1
}

# Мастер подключения: он и есть обычный способ поставить канал, поэтому обязан
# существовать, быть синтаксически целым и уметь проверять предусловия, ничего не
# меняя. Полный прогон здесь недоступен — он требует настоящего бота и правит
# файлы в домашнем каталоге; проверяется то, что проверяемо без побочных эффектов.
SETUP="$(dirname "$BOT_DIR")/setup.sh"
[[ -f "$SETUP" ]] || { echo "FAIL: нет мастера подключения канала: channel/setup.sh"; exit 1; }
bash -n "$SETUP" || { echo "FAIL: channel/setup.sh не разбирается как shell-скрипт"; exit 1; }
grep -qF -- '--check' "$SETUP" || { echo "FAIL: у мастера нет режима --check (проверить, ничего не меняя)"; exit 1; }
for marker in 'getUpdates' 'chmod 600' '/notify' 'curl_hidden' 'PAIR_CODE' 'STARTED_AT'; do
  grep -qF -- "$marker" "$SETUP" || {
    echo "FAIL: мастер потерял шаг: ${marker}"
    echo "      Несущее: chat id определяется сам, но по одноразовому слову и только из свежих"
    echo "      обновлений (иначе владельцем канала станет первый посторонний, написавший боту);"
    echo "      секреты уходят в curl через --config, а не argv (ps показывает argv всем);"
    echo "      права на файл секрета 600; проверка сквозная, настоящим сообщением."
    exit 1
  }
done

echo "PASS ($ran проверок)"
