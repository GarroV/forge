#!/usr/bin/env python3
"""Страж изображений: картинка не попадает в контекст дорогой роли.

Ставится на PreToolUse:Read и решает один вопрос — имеет ли право эта роль
прочитать это изображение прямо сейчас.

Зачем это существует. Скриншот — самый дорогой объект, который может попасть в
контекст агента: один снимок страницы весит 30-180 тысяч токенов и остаётся в
контексте до конца жизни агента, перечитываясь из кэша на каждом следующем ходу.
Замер одной реальной стройки (6 сентября 2026): блок-агенты прочитали 40
изображений на 1,8 млн токенов; удержание этих картинок в контексте стоило
132 млн токенов чтения кэша — **20% всего расхода блок-агентов**, при том что
все они на opus. Самый дорогой снимок обошёлся в 23 млн токенов: 181 тысяча
токенов, прочитанная на 254-м ходу из 382, то есть перечитанная 128 раз.

Разбор дефекта, а не жадность: сама сверка экрана с эталоном обязательна и
находит класс дефектов, который не видят ни тесты, ни сверка со спекой. Неверна
не сверка, а место: её делает тот, кто дороже всех и живёт дольше всех. Роль
`forge-visual-checker` смотрит те же картинки на sonnet, живёт десятки ходов
вместо сотен и возвращает текстовый вердикт — те же данные за проценты цены.

Три вещи, которые страж обязан делать безошибочно:

1. **Молчать везде, кроме активной стройки.** Он стоит глобально и срабатывает в
   каждой сессии на каждой машине. Нет маркера стройки — выход без решения:
   владелец, читающий свой скриншот в обычной сессии, не должен натыкаться на
   правило чужой подсистемы.
2. **Пропускать того, кому это положено.** `forge-visual-checker` для того и
   заведён, чтобы смотреть картинки; запрет ему превратил бы сверку в
   невозможную.
3. **Отказывать словами, а не молча.** Отказ обязан называть замену — иначе агент
   решит, что сверка недоступна, и тихо её пропустит. Это ровно тот исход, ради
   предотвращения которого правило и написано.

Коды возврата — контракт харнесса: JSON с `permissionDecision: deny` запрещает
вызов и отдаёт модели причину, выход `0` без вывода разрешает. Любой сбой внутри
стража обязан быть разрешением: сломанный страж не должен превращаться в
запрещённое чтение.
"""

import importlib.util
import json
import os
import sys
from pathlib import Path

# Роль, которой смотреть картинки положено: она для этого и заведена.
VISUAL_ROLE = "forge-visual-checker"

# Расширения, которые харнесс отдаёт модели как изображение, а не как текст.
IMAGE_SUFFIXES = {".png", ".jpg", ".jpeg", ".webp", ".gif", ".bmp", ".avif"}

# Ниже этого размера чтение не стоит вмешательства. Порог не в токенах, а в
# байтах файла, потому что это единственное, что страж знает до чтения; 50 КБ
# png — это примерно 19 тысяч токенов в контексте. Мелочь такого размера (иконка,
# вырезанный фрагмент, диаграмма) иногда действительно нужна на месте, и запрет
# на неё стоил бы дороже самой картинки. Всё, что крупнее, — снимок экрана.
MIN_BLOCK_BYTES = 50_000


def load_keep_building():
    """Сторож непрерывности держит общие для хуков понятия: корень проекта и маркер."""
    path = Path(__file__).resolve().parent / "keep-building.py"
    spec = importlib.util.spec_from_file_location("forge_keep_building", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def caller_role(payload: dict) -> str:
    """Роль вызывающего — из метаданных рядом с его транскриптом.

    Субагент пишет в `<сессия>/subagents/agent-<id>.jsonl`, и рядом лежит
    `agent-<id>.meta.json` с полем `agentType`. Это единственный доступный хуку
    способ отличить роль от роли: в самом payload роли нет. Главная сессия
    (диспетчер) метафайла не имеет — для неё роль пустая, и это верно: диспетчер
    не исключение из правила, он такой же дорогой долгожитель.
    """
    transcript = payload.get("transcript_path")
    if not transcript:
        return ""
    path = Path(transcript)
    name = path.name
    if not (name.startswith("agent-") and name.endswith(".jsonl")):
        return ""
    meta = path.with_name(name[: -len(".jsonl")] + ".meta.json")
    try:
        return str(json.loads(meta.read_text(encoding="utf-8")).get("agentType") or "")
    except Exception:
        return ""


def deny(reason: str) -> None:
    print(json.dumps({
        "hookSpecificOutput": {
            "hookEventName": "PreToolUse",
            "permissionDecision": "deny",
            "permissionDecisionReason": reason,
        }
    }, ensure_ascii=False))


def main() -> int:
    try:
        payload = json.loads(sys.stdin.read() or "{}")
    except Exception:
        return 0
    if not isinstance(payload, dict) or payload.get("tool_name") != "Read":
        return 0

    tool_input = payload.get("tool_input") or {}
    raw_path = tool_input.get("file_path") or ""
    if not raw_path:
        return 0
    target = Path(str(raw_path))
    if target.suffix.lower() not in IMAGE_SUFFIXES:
        return 0

    # Роль-исключение проверяется до маркера: она дешёвая и вне стройки тоже.
    if caller_role(payload) == VISUAL_ROLE:
        return 0

    try:
        kb = load_keep_building()
        root = kb.project_root(payload.get("cwd") or os.getcwd())
        if not kb.read_marker(kb.marker_path(root)):
            return 0
    except Exception:
        return 0

    try:
        size = target.stat().st_size
    except Exception:
        # Файла нет или он недоступен — это забота Read, а не стража.
        return 0
    if size < MIN_BLOCK_BYTES:
        return 0

    approx_tokens = int(size * 4 / 3 / 3.5)
    deny(
        f"Изображение в контекст не читается: {target.name} весит {size // 1024} КБ "
        f"(≈{approx_tokens // 1000} тыс. токенов) и останется в контексте до конца твоей "
        f"работы, перечитываясь на каждом ходу. Замер стройки: 40 таких снимков стоили "
        f"20% всего расхода блок-агентов.\n\n"
        f"Сверку экрана делает субагент `{VISUAL_ROLE}` (`subagent_type: \"{VISUAL_ROLE}\"`, "
        f"модель у роли своя): передай ему путь к снимку и путь к эталонному модулю, а также "
        f"что именно проверить — он вернёт текстом список расхождений. Сверку не пропускай: "
        f"класс дефектов, который виден только глазами, — 13% замера, и ни тест, ни сверка "
        f"со спекой его не ловят.\n\n"
        f"Снимок нужен владельцу — прикладывай к сообщению путь к файлу, не читая его сам."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
